BookPageReference bookReferenceFor({
  required String subject,
  required String unit,
  required String lesson,
}) {
  for (final ref in v12VerifiedBookReferences) {
    if (ref.subject == subject && ref.unit == unit && ref.lesson == lesson) {
      return ref;
    }
  }

  // The current official books exist for these subjects, but this build refuses
  // to invent a page number until the exact 2026/27 PDF has been indexed.
  return BookPageReference(
    subject: subject,
    unit: unit,
    lesson: lesson,
    bookTitle: _subjectBookTitles[subject] ?? 'كتاب الطالب الرسمي للصف الثاني عشر',
    publisher: _nccd,
    referenceStatus: 'بانتظار مطابقة الصفحة من نسخة الكتاب الرسمية',
    note: 'لن يعرض مُوَجِّه رقم صفحة تقديريًا. يُضاف الرقم بعد مطابقة نسخة الكتاب الرسمية نفسها.',
  );
}

